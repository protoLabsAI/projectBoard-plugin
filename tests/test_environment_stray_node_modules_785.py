"""A cache-only ``node_modules`` no package manager manages is not an environment (#785)."""

import json
import logging
from pathlib import Path

import pytest

from project_board import worktree
from test_promoted_worktree_environment import git

STRAY = "packages/ui/src/node_modules"


@pytest.fixture
def tree(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    git(repo, "init", "-b", "main")
    git(repo, "config", "user.email", "test@example.com")
    git(repo, "config", "user.name", "Test")
    (repo / ".gitignore").write_text("node_modules/\n.worktrees/\n")
    git(repo, "add", ".")
    git(repo, "commit", "-m", "base")
    wt = repo / ".worktrees/card"
    git(repo, "worktree", "add", "-b", "card", str(wt))
    return wt


def cache_only(wt, rel=STRAY):
    cache = wt / rel / ".cache/pl-ui-tests"
    cache.mkdir(parents=True)
    (cache / "bundle.js").write_text("cached test bundle")
    return wt / rel


def pending(wt, environments):
    marker = Path(worktree._environment_marker(str(wt)))
    marker.write_text(json.dumps({"source": str(wt), "environments": environments}))
    return marker


def test_cache_only_node_modules_is_not_an_environment(tree, caplog):
    stray = cache_only(tree)
    with caplog.at_level(logging.INFO, logger=worktree.log.name):
        assert worktree._installed_environments(str(tree)) == []
        assert worktree._installed_environments(str(tree)) == []
    # Logged once per directory, not once per scan.
    assert [r.getMessage() for r in caplog.records if "stray node_modules" in r.getMessage()] == [
        f"[project_board] ignoring stray node_modules {stray}: no package manager manages it (#785)"
    ]


@pytest.mark.parametrize("state", [".modules.yaml", ".package-lock.json", ".yarn-state.yml", ".yarn-integrity"])
def test_package_manager_state_makes_it_an_environment(tree, state):
    (cache_only(tree) / state).write_text("")
    assert worktree._installed_environments(str(tree)) == [STRAY]


def test_node_modules_under_a_package_root_is_an_environment(tree):
    cache_only(tree)
    (tree / "packages/ui/src/package.json").write_text("{}")
    assert worktree._installed_environments(str(tree)) == [STRAY]


@pytest.mark.parametrize("kind", ["package", "bin", "empty", "link"])
def test_anything_but_a_plain_cache_directory_stays_an_environment(tree, kind):
    # Not managed by the letter of #785, and not provably a cache either: keep requiring it.
    if kind == "package":
        (cache_only(tree) / "react").mkdir()
    elif kind == "bin":
        (cache_only(tree) / ".bin").mkdir()
    elif kind == "empty":
        (tree / STRAY).mkdir(parents=True)
    else:
        target = cache_only(tree, "elsewhere/node_modules")
        (tree / "elsewhere/package.json").write_text("{}")
        (tree / "packages/ui/src").mkdir(parents=True)
        (tree / STRAY).symlink_to(target, target_is_directory=True)
    assert STRAY in worktree._installed_environments(str(tree))


async def test_stray_directory_does_not_block_restore_and_is_left_alone(tree):
    stray = cache_only(tree)
    marker = pending(tree, worktree._installed_environments(str(tree)))
    # No environment to rebuild: no setup_cmd is needed, not even the lockfile default.
    await worktree.restore_worktree_environment(str(tree), "", env=None, timeout=5)
    assert not marker.exists()
    assert not list(marker.parent.glob("board-old-environment-*"))
    assert (stray / ".cache/pl-ui-tests/bundle.js").read_text() == "cached test bundle"


async def test_old_marker_naming_a_stray_directory_does_not_block_restore(tree):
    # The marker ds-awm was left with on 2026-11-17: written before strays were ignored.
    stray = cache_only(tree)
    marker = pending(tree, [STRAY])
    await worktree.restore_worktree_environment(str(tree), "touch setup-ran", env=None, timeout=5)
    assert (tree / "setup-ran").exists()
    assert not marker.exists()
    # Neither quarantined nor deleted.
    assert (stray / ".cache/pl-ui-tests/bundle.js").read_text() == "cached test bundle"


async def test_stray_directory_beside_a_real_environment_only_the_real_one_is_rebuilt(tree):
    stray = cache_only(tree)
    (tree / "package.json").write_text("{}")
    (tree / "node_modules").mkdir()
    (tree / "node_modules/original").write_text("old install")
    marker = pending(tree, ["node_modules", STRAY])
    await worktree.restore_worktree_environment(
        str(tree), "mkdir node_modules && touch node_modules/.modules.yaml", env=None, timeout=5
    )
    assert not marker.exists()
    assert not (tree / "node_modules/original").exists()
    assert (stray / ".cache/pl-ui-tests/bundle.js").exists()


@pytest.mark.parametrize("managed_by", [".modules.yaml", "package.json"])
async def test_managed_node_modules_is_still_required_after_setup(tree, managed_by):
    managed = cache_only(tree)
    if managed_by == "package.json":
        (managed.parent / "package.json").write_text("{}")
    else:
        (managed / managed_by).write_text("")
    environments = worktree._installed_environments(str(tree))
    assert environments == [STRAY]
    marker = pending(tree, environments)
    with pytest.raises(worktree.EnvironmentPreparationError) as error:
        await worktree.restore_worktree_environment(str(tree), "touch setup-ran", env=None, timeout=5)
    assert f"setup_cmd did not recreate environments: ['{STRAY}']" in str(error.value)
    # Rolled back and still pending, so a repaired setup_cmd can finish it.
    assert marker.exists()
    assert (managed / ".cache/pl-ui-tests/bundle.js").exists()
    await worktree.restore_worktree_environment(str(tree), f"mkdir -p {STRAY}", env=None, timeout=5)
    assert not marker.exists()
    assert not (managed / ".cache").exists()
